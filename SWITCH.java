class SWITCH{
    void main(){
        int m=4;
        
        switch(m){
            case 1:
                IO.println("VERY SMALL");
                break;
                case 2:
                    IO.println("small");
                    break;
                    case 3:
                        IO.println("large");
                        break;
                        case 4:
                            IO.println("extra large");
                            break;
                            default:
                                IO.println("invalid");


        }
    }
}